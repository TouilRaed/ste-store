/**
 * Regenerates supabase/seed.sql from the demo catalogue in
 * src/lib/catalog/fallback.ts so the two can never drift.
 *
 *   npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const { fallbackCollections, fallbackProducts } = await import("../src/lib/catalog/fallback.ts");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const q = (value) => (value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`);
// Postgres can't infer the element type of a bare `array[]`.
const arr = (values) =>
  values.length === 0 ? "'{}'::text[]" : `array[${values.map(q).join(", ")}]`;
const num = (value) => (value === null || value === undefined ? "null" : String(value));

const collectionSlugById = new Map(fallbackCollections.map((c) => [c.id, c.slug]));

const collectionRows = fallbackCollections
  .map((c) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.tagline)}, ${num(c.position)})`)
  .join(",\n");

const productRows = fallbackProducts
  .map(
    (p) => `  (
    ${q(p.slug)},
    ${q(p.name)},
    ${q(p.description)},
    ${arr(p.details)},
    ${num(p.price_cents)}, ${num(p.compare_at_cents)}, ${q(p.currency)},
    ${arr(p.images)},
    ${arr(p.sizes)}, ${arr(p.colors)},
    (select id from public.collections where slug = ${q(collectionSlugById.get(p.collection_id))}),
    ${q(p.gender)}, ${num(p.stock)}, ${p.is_featured}, ${arr(p.tags ?? [])}
  )`,
  )
  .join(",\n");

// An empty list must not emit `values` with no rows — that is invalid SQL.
const collectionsBlock = fallbackCollections.length
  ? `insert into public.collections (slug, name, tagline, position) values
${collectionRows}
on conflict (slug) do update
  set name = excluded.name,
      tagline = excluded.tagline,
      position = excluded.position;
`
  : "-- no collections in the catalogue";

const productsBlock = fallbackProducts.length
  ? `insert into public.products
  (slug, name, description, details, price_cents, compare_at_cents, currency, images, sizes, colors, collection_id, gender, stock, is_featured, tags)
values
${productRows}
on conflict (slug) do update set
  name             = excluded.name,
  description      = excluded.description,
  details          = excluded.details,
  price_cents      = excluded.price_cents,
  compare_at_cents = excluded.compare_at_cents,
  currency         = excluded.currency,
  images           = excluded.images,
  sizes            = excluded.sizes,
  colors           = excluded.colors,
  collection_id    = excluded.collection_id,
  gender           = excluded.gender,
  stock            = excluded.stock,
  is_featured      = excluded.is_featured,
  tags             = excluded.tags;
`
  : "-- no products in the catalogue";

const sql = `-- Seed catalogue. Run after schema.sql.
-- GENERATED by scripts/generate-seed.mjs from src/lib/catalog/fallback.ts — do not edit by hand.
-- Safe to re-run: upserts on slug.

${collectionsBlock}
${productsBlock}`;

writeFileSync(join(root, "supabase", "seed.sql"), sql, "utf8");
console.log(`seed.sql written — ${fallbackCollections.length} collections, ${fallbackProducts.length} products`);
